"""Report generation for benchmark results."""

import json
from datetime import datetime
from pathlib import Path
from typing import Any

from jinja2 import Template
from rich.console import Console
from rich.table import Table

from benchmark.metrics import BenchmarkMetrics, TechniqueMetrics

console = Console()


MARKDOWN_TEMPLATE = """# SOC Detection Benchmark Report

**Run ID:** {{ metrics.run_id }}
**Date:** {{ metrics.start_time.strftime('%Y-%m-%d %H:%M:%S') }}
**Duration:** {{ duration_seconds }}s

## Summary

| Metric | Value |
|--------|-------|
| Total Attacks | {{ metrics.total_attacks }} |
| Detected | {{ metrics.total_detected }} |
| **Overall Detection Rate** | **{{ "%.1f"|format(metrics.overall_detection_rate * 100) }}%** |
| Mean Time to Detect | {{ "%.2f"|format(metrics.mean_time_to_detect_seconds) if metrics.mean_time_to_detect_seconds else "N/A" }}s |
| False Positive Rate | {{ "%.1f"|format(metrics.false_positive_rate_per_hour) }}/hour |
| Alert Volume per Attack | {{ "%.1f"|format(metrics.alert_volume_per_attack) }} |

## Detection by Technique

| Technique | Tactic | Tests | Detected | Rate | MTTD |
|-----------|--------|-------|----------|------|------|
{% for t in metrics.technique_metrics -%}
| {{ t.technique_id }} ({{ t.technique_name }}) | {{ t.tactic }} | {{ t.tests_executed }} | {{ t.tests_detected }} | {{ "%.0f"|format(t.detection_rate * 100) }}% | {{ "%.2fs"|format(t.mean_time_to_detect_seconds) if t.mean_time_to_detect_seconds else "N/A" }} |
{% endfor %}

## Detection Gaps

{% if metrics.detection_gaps -%}
The following techniques had **0% detection rate**:

{% for gap in metrics.detection_gaps -%}
- {{ gap }}
{% endfor %}

### Recommendations

1. Review audit rules for missing syscall coverage
2. Check if Sigma rules exist for these techniques
3. Verify log ingestion pipeline is capturing relevant events
{% else -%}
No detection gaps identified - all techniques had at least partial detection.
{% endif %}

## Methodology

- **Attack Framework:** Atomic Red Team
- **Detection Engine:** Elasticsearch with Sigma rules
- **Log Sources:** auditd, syslog, auth.log
- **Techniques Tested:** {{ metrics.total_attacks }} across {{ metrics.technique_metrics|length }} ATT&CK techniques

## Reproducibility

To reproduce this benchmark:

```bash
# Start the lab environment
make up

# Run baseline for FP measurement
make run-baseline

# Execute attacks
make run-attacks

# Generate report
make report
```

---
*Generated by SOC Detection Benchmark v1.0.0*
"""


class ReportGenerator:
    """Generates benchmark reports in various formats."""

    def __init__(self, output_dir: Path = Path("results")):
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_markdown(self, metrics: BenchmarkMetrics) -> str:
        """Generate a Markdown report."""
        template = Template(MARKDOWN_TEMPLATE)

        duration_seconds = (metrics.end_time - metrics.start_time).total_seconds()

        return template.render(
            metrics=metrics,
            duration_seconds=int(duration_seconds),
        )

    def generate_json(self, metrics: BenchmarkMetrics) -> dict[str, Any]:
        """Generate a JSON-serializable report."""
        return {
            "run_id": metrics.run_id,
            "start_time": metrics.start_time.isoformat(),
            "end_time": metrics.end_time.isoformat(),
            "duration_seconds": (metrics.end_time - metrics.start_time).total_seconds(),
            "summary": {
                "total_attacks": metrics.total_attacks,
                "total_detected": metrics.total_detected,
                "overall_detection_rate": metrics.overall_detection_rate,
                "mean_time_to_detect_seconds": metrics.mean_time_to_detect_seconds,
                "false_positive_rate_per_hour": metrics.false_positive_rate_per_hour,
                "alert_volume_per_attack": metrics.alert_volume_per_attack,
            },
            "technique_metrics": [
                {
                    "technique_id": t.technique_id,
                    "technique_name": t.technique_name,
                    "tactic": t.tactic,
                    "tests_executed": t.tests_executed,
                    "tests_detected": t.tests_detected,
                    "detection_rate": t.detection_rate,
                    "mean_time_to_detect_seconds": t.mean_time_to_detect_seconds,
                    "alert_count": t.alert_count,
                    "false_negative_count": t.false_negative_count,
                }
                for t in metrics.technique_metrics
            ],
            "detection_gaps": metrics.detection_gaps,
        }

    def save_report(self, metrics: BenchmarkMetrics) -> dict[str, Path]:
        """Save report in multiple formats."""
        timestamp = metrics.run_id

        # Save Markdown
        md_path = self.output_dir / f"report_{timestamp}.md"
        md_content = self.generate_markdown(metrics)
        md_path.write_text(md_content)

        # Save JSON
        json_path = self.output_dir / f"report_{timestamp}.json"
        json_content = self.generate_json(metrics)
        json_path.write_text(json.dumps(json_content, indent=2))

        # Save latest symlinks
        latest_md = self.output_dir / "report_latest.md"
        latest_json = self.output_dir / "report_latest.json"

        # Remove existing symlinks
        latest_md.unlink(missing_ok=True)
        latest_json.unlink(missing_ok=True)

        # Create new symlinks
        latest_md.symlink_to(md_path.name)
        latest_json.symlink_to(json_path.name)

        return {
            "markdown": md_path,
            "json": json_path,
        }

    def print_summary(self, metrics: BenchmarkMetrics) -> None:
        """Print a summary table to the console."""
        console.print("\n[bold blue]Detection Benchmark Results[/bold blue]\n")

        # Summary table
        summary = Table(title="Summary", show_header=True)
        summary.add_column("Metric", style="cyan")
        summary.add_column("Value", style="green")

        summary.add_row("Total Attacks", str(metrics.total_attacks))
        summary.add_row("Detected", str(metrics.total_detected))
        summary.add_row(
            "Detection Rate",
            f"{metrics.overall_detection_rate * 100:.1f}%",
        )
        summary.add_row(
            "Mean TTD",
            f"{metrics.mean_time_to_detect_seconds:.2f}s"
            if metrics.mean_time_to_detect_seconds
            else "N/A",
        )
        summary.add_row(
            "FP Rate",
            f"{metrics.false_positive_rate_per_hour:.1f}/hour",
        )

        console.print(summary)

        # Technique breakdown
        techniques = Table(title="\nDetection by Technique", show_header=True)
        techniques.add_column("Technique", style="cyan")
        techniques.add_column("Tactic")
        techniques.add_column("Rate", justify="right")
        techniques.add_column("MTTD", justify="right")

        for t in metrics.technique_metrics:
            rate_style = (
                "green"
                if t.detection_rate >= 0.8
                else "yellow"
                if t.detection_rate >= 0.5
                else "red"
            )
            techniques.add_row(
                f"{t.technique_id}",
                t.tactic,
                f"[{rate_style}]{t.detection_rate * 100:.0f}%[/{rate_style}]",
                f"{t.mean_time_to_detect_seconds:.2f}s"
                if t.mean_time_to_detect_seconds
                else "N/A",
            )

        console.print(techniques)

        # Detection gaps
        if metrics.detection_gaps:
            console.print("\n[bold red]Detection Gaps:[/bold red]")
            for gap in metrics.detection_gaps:
                console.print(f"  - {gap}")


def generate_report(
    metrics: BenchmarkMetrics,
    output_dir: str = "results",
) -> dict[str, Path]:
    """Generate and save a benchmark report."""
    generator = ReportGenerator(output_dir=Path(output_dir))

    # Print summary to console
    generator.print_summary(metrics)

    # Save reports
    paths = generator.save_report(metrics)

    console.print(f"\n[green]Reports saved to:[/green]")
    console.print(f"  Markdown: {paths['markdown']}")
    console.print(f"  JSON: {paths['json']}")

    return paths
